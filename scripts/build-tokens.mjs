// Turn the Figma variables in tokens/figma-variables.json into CSS custom
// properties and typography classes, scoped to the design system's root class.
//
//   node scripts/build-tokens.mjs   (or: npm run tokens)
//
// Naming: colours use the variable's last path segment, lower-cased, with any
// "pgn-" prefix dropped ("Backgrounds/Secondary/wgu-bg-sec-emphasis" becomes
// --wgu-bg-sec-emphasis). Spacing "48px" becomes --wgu-space-48, radii become
// --wgu-radius-*, and each text style becomes --wgu-type-<name>-* plus a
// .wgu-type-<name> class.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(resolve(root, 'tokens/figma-variables.json'), 'utf8'));

const RADII = { xl: 'xl', xxl: 'xxl', 'rounded-pill': 'pill' };
// The design system's own font faces (src/fonts.scss), then the plain names.
const FALLBACK_FONTS = {
  Sora: "'Exemplar Sora', 'Sora', Arial, sans-serif",
  Lato: "'Exemplar Lato', 'Lato', Arial, sans-serif",
};

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function colourName(path) {
  const leaf = path.split('/').pop().toLowerCase().replace(/^pgn-/, '');
  return `--${leaf.startsWith('wgu-') ? leaf : `wgu-${leaf}`}`;
}

function typeName(path) {
  // "Body/Body 18 - Bold" -> "body-18-bold", "Header/H4" -> "h4",
  // "Action (Links, Clickable)/Action 16" -> "action-16".
  return slug(path.split('/').pop());
}

const lines = [];
const seen = new Map();
const add = (name, value, origin) => {
  if (seen.has(name) && seen.get(name).value !== value) {
    throw new Error(`${name} is ${seen.get(name).value} (${seen.get(name).origin}) and ${value} (${origin})`);
  }
  if (!seen.has(name)) {
    seen.set(name, { value, origin });
    lines.push(`  ${name}: ${value}; // ${origin}`);
  }
};

for (const [path, value] of Object.entries(source.variables)) {
  if (/^#[0-9a-f]{3,8}$/i.test(value)) {
    add(colourName(path), value.toLowerCase(), path);
  } else if (/^\d+px$/.test(path)) {
    add(`--wgu-space-${path.replace('px', '')}`, `${value}px`, path);
  } else if (path === 'Body') {
    add('--wgu-space-body', `${value}px`, path);
  } else if (RADII[path]) {
    add(`--wgu-radius-${RADII[path]}`, `${value}px`, path);
  } else {
    throw new Error(`No naming rule for Figma variable "${path}"`);
  }
}

const classes = [];
for (const [path, style] of Object.entries(source.typography)) {
  const name = typeName(path);
  const family = FALLBACK_FONTS[style.family] ?? `'${style.family}', sans-serif`;
  add(`--wgu-type-${name}-family`, family, path);
  add(`--wgu-type-${name}-size`, `${style.size}px`, path);
  add(`--wgu-type-${name}-weight`, String(style.weight), path);
  add(`--wgu-type-${name}-line`, `${style.lineHeight}px`, path);
  classes.push(
    `  .wgu-type-${name} {\n`
    + `    font-family: var(--wgu-type-${name}-family);\n`
    + `    font-size: var(--wgu-type-${name}-size);\n`
    + `    font-weight: var(--wgu-type-${name}-weight);\n`
    + `    line-height: var(--wgu-type-${name}-line);\n`
    + '  }',
  );
}

const output = `// Generated by scripts/build-tokens.mjs from tokens/figma-variables.json.
// Do not edit by hand: change the JSON and run \`npm run tokens\`.

@mixin wgu-tokens {
${lines.join('\n')}
}

@mixin wgu-type-classes {
${classes.join('\n\n')}
}
`;

writeFileSync(resolve(root, 'src/tokens.generated.scss'), output);
console.log(`Wrote ${seen.size} tokens and ${classes.length} text styles to src/tokens.generated.scss`);
